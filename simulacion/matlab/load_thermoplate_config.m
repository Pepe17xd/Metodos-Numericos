function cfg = load_thermoplate_config(path)
%LOAD_THERMOPLATE_CONFIG Read shared JSON assumptions and validate them.
    if nargin<1 || isempty(path)
        here=fileparts(mfilename('fullpath'));
        path=fullfile(here,'..','configuracion','modelo_base.json');
    end
    raw=jsondecode(fileread(path));
    o=struct('Lx',raw.plate.Lx_m,'Ly',raw.plate.Ly_m, ...
        'thickness',raw.plate.thickness_m,'k',raw.plate.k_W_mK, ...
        'Tb',raw.plate.boundary_temperature_C, ...
        'cpu',struct('x',raw.sources.cpu.x0_m,'y',raw.sources.cpu.y0_m, ...
          'width',raw.sources.cpu.width_m,'height',raw.sources.cpu.height_m, ...
          'power',raw.sources.cpu.power_W), ...
        'gpu',struct('x',raw.sources.gpu.x0_m,'y',raw.sources.gpu.y0_m, ...
          'width',raw.sources.gpu.width_m,'height',raw.sources.gpu.height_m, ...
          'power',raw.sources.gpu.power_W), ...
        'grids',double(raw.grids_nodes),'baselineGrid',double(raw.baseline_grid_nodes(:)'), ...
        'tolerance',raw.solver.relative_residual_tolerance, ...
        'maxIterations',raw.solver.max_iterations, ...
        'initialTemperature',raw.plate.boundary_temperature_C, ...
        'checkpointFractions',[0.01 0.1 0.5 1]);
    cfg=thermoplate_config(o);
    cfg.configPath=path; cfg.assumptions=raw.assumptions; cfg.units=raw.units;
end
