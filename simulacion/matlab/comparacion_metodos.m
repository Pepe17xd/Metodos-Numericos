function tabla = comparacion_metodos(modelo, solucion_directa, gauss_seidel, gradiente_conjugado)
%COMPARACION_METODOS Resume ambos métodos con la misma referencia directa.
    directa = metricas_temperatura(modelo,solucion_directa);
    gs = metricas_temperatura(modelo,gauss_seidel.x);
    cg = metricas_temperatura(modelo,gradiente_conjugado.x);
    residuo_directo = norm(modelo.b-modelo.A*solucion_directa)/norm(modelo.b);
    tabla = table( ...
        ["Directa dispersa"; string(gauss_seidel.solver); string(gradiente_conjugado.solver)], ...
        [1; gauss_seidel.iterations; gradiente_conjugado.iterations], ...
        [residuo_directo; gauss_seidel.relativeResidual; gradiente_conjugado.relativeResidual], ...
        [directa.Tmax_C; gs.Tmax_C; cg.Tmax_C], ...
        [NaN; gauss_seidel.relativeStepError; NaN], ...
        'VariableNames',{'metodo','iteraciones','residuo_relativo','temperatura_maxima_C','error_iterativo_GS'});
end
